-- ==========================================================
-- เพิ่มตาราง roles (ตำแหน่ง/ประเภทกีฬา) ให้แอดมินเพิ่มเองได้จากหน้าเว็บ
-- รันไฟล์นี้ใน pgAdmin Query Tool (เลือกฐานข้อมูล sports_day ก่อน)
-- ==========================================================

CREATE TABLE roles (
  id   SERIAL PRIMARY KEY,
  name TEXT UNIQUE NOT NULL
);

