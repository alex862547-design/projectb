ON CONFLICT (name) DO NOTHING;

-- เผื่อมีนักศึกษาบางคนที่มีตำแหน่งเป็นข้อความอื่นอยู่แล้ว (เช่นเคยพิมพ์เองก่อนหน้านี้)
-- ให้ดึงมาใส่ในลิสต์ roles ด้วย จะได้ไม่หายไปจากดรอปดาวน์
INSERT INTO roles (name)
SELECT DISTINCT role FROM students WHERE role IS NOT NULL AND role <> ''
ON CONFLICT (name) DO NOTHING;
