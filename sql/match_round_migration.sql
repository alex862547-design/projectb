ALTER TABLE matches ADD COLUMN IF NOT EXISTS round TEXT;

-- นัดเดิมที่มีอยู่แล้ว (สปอร์ตละ 1 นัด) ถือเป็นนัดชิงชนะเลิศไปก่อน แอดมินจัดใหม่ทีหลังได้
UPDATE matches SET round = 'รอบชิงชนะเลิศ' WHERE round IS NULL;
