ALTER TABLE students ADD COLUMN IF NOT EXISTS year INT;

-- นักศึกษาเดิมที่ยังไม่มีชั้นปี ให้ตั้งเป็นปีที่ 1 ไปก่อน แอดมินแก้ทีหลังได้
UPDATE students SET year = 1 WHERE year IS NULL;
